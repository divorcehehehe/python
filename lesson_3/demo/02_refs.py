# ссылки и копии: одно имя или два имени одного списка
a = [4, 5, 6]
b = a               # это НЕ копия, а второе имя того же списка
b.append(10)
print('a =', a)     # изменился тоже
print('b =', b)

# независимая копия
a = [4, 5, 6]
c = a.copy()        # то же самое даёт срез a[:]
c.append(10)
print('a =', a)     # остался прежним
print('c =', c)

# копия поверхностная: вложенные списки остаются общими
table = [[1, 2], [3, 4]]
shallow = table.copy()
shallow[0].append(99)
print(table)
